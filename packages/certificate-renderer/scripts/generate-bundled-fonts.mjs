import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const resources = resolve(root, "resources", "noto-thai-v2.002");
const output = resolve(root, "src", "generated-bundled-fonts.ts");
const fonts = [
  ["Noto Sans Thai", 400, "NotoSansThai-Regular.ttf"],
  ["Noto Sans Thai", 700, "NotoSansThai-Bold.ttf"],
  ["Noto Serif Thai", 400, "NotoSerifThai-Regular.ttf"],
  ["Noto Serif Thai", 700, "NotoSerifThai-Bold.ttf"]
];

const records = await Promise.all(fonts.map(async ([family, weight, file]) => {
  const bytes = await readFile(resolve(resources, file));
  return { family, weight, sha256: createHash("sha256").update(bytes).digest("hex"), base64: bytes.toString("base64") };
}));

await writeFile(output, `// Generated by scripts/generate-bundled-fonts.mjs. Do not edit.\nexport const BUNDLED_NOTO_FONTS = ${JSON.stringify(records)} as const;\n`, "utf8");
